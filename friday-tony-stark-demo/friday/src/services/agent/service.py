WEATHER_COMMAND_TOKENS = (
    "weather",
    "forecast",
    "temperature",
    "rain",
    "humidity",
    "wind",
)

WEATHER_LOCATION_SKIP_WORDS = {
    "weather", "forecast", "temperature", "today", "tomorrow", "now",
    "current", "currently", "in", "at", "for", "the", "is", "like",
    "please", "tell", "me", "what", "how", "tomorrow",
}



LLM_NOT_CONFIGURED_MESSAGE = (
    "I received your question, but the backend does not have OPENAI_API_KEY "
    "or FRIDAY_LLM_API_KEY configured yet. Add a provider key in the backend "
    ".env file and I will answer with the language model instead of rule-based fallback."
)


def _normalize_text(value: str) -> str:
    decomposed = unicodedata.normalize("NFD", value)
    without_marks = "".join(
        character for character in decomposed if unicodedata.category(character) != "Mn"
    )
    return " ".join(without_marks.lower().split())


def _is_computer_command(message: str) -> bool:
    normalized = _normalize_text(message)
    return any(token in normalized for token in COMPUTER_COMMAND_TOKENS)


def _is_gmail_command(message: str) -> bool:
    normalized = _normalize_text(message)
    return any(token in normalized for token in GMAIL_COMMAND_TOKENS)


def _is_weather_command(message: str) -> bool:
    normalized = _normalize_text(message)
    return any(token in normalized for token in WEATHER_COMMAND_TOKENS)


def _title_location(value: str) -> str:
    replacements = {
        "da lat": "Da Lat",
        "da nang": "Da Nang",
        "ha noi": "Ha Noi",
        "ho chi minh": "Ho Chi Minh",
        "sai gon": "Sai Gon",
        "can tho": "Can Tho",
        "nha trang": "Nha Trang",
        "vung tau": "Vung Tau",
        "buon ma thuot": "Buon Ma Thuot",
    }
    normalized = _normalize_text(value)
    if normalized in replacements:
        return replacements[normalized]
    return " ".join(token.capitalize() for token in normalized.split())


def _extract_weather_location(message: str) -> tuple[str, str]:
    normalized = _normalize_text(message)

    explicit_location = re.search(r"\b(?:in|at|for)\s+(.+)$", normalized)
    if explicit_location:
        candidate = re.sub(
            r"\b(today|tomorrow|now|currently|please|like)\b",
            " ",
            explicit_location.group(1),
        )
        candidate = re.sub(r"\s+", " ", candidate).strip(" ,.!?;:-")
        if candidate:
            city = resolve_vietnam_city(candidate)
            if city:
                return str(city.get("name") or candidate), _title_location(candidate)
            return candidate, _title_location(candidate)

    tokens = [token for token in normalized.split() if token not in WEATHER_LOCATION_SKIP_WORDS]

    for size in range(min(4, len(tokens)), 0, -1):
        for index in range(0, len(tokens) - size + 1):
            candidate = " ".join(tokens[index:index + size]).strip()
            if len(candidate) < 3:
                continue
            city = resolve_vietnam_city(candidate)
            if city:
                return str(city.get("name") or candidate), _title_location(candidate)

    for pattern in (
        r"\b(?:in|at|for)\s+(.+)$",
        r"\b(?:weather|forecast)\s+(?:in|at|for)?\s*(.+)$",
        r"^(.+?)\s+(?:weather|forecast)(?:\s+(?:today|tomorrow))?$",
    ):
        match = re.search(pattern, normalized)
        if not match:
            continue
        candidate = match.group(1)
        candidate = re.sub(r"\b(today|tomorrow|now|currently|please|like)\b", " ", candidate)
        candidate = re.sub(r"\s+", " ", candidate).strip(" ,.!?;:-")
        if candidate:
            city = resolve_vietnam_city(candidate)
            if city:
                return str(city.get("name") or candidate), _title_location(candidate)
            return candidate, _title_location(candidate)

    location = resolve_runtime_location()
    return location.city, location.display_name


async def _build_weather_reply(message: str) -> str:
    city, display_location = _extract_weather_location(message)
    is_tomorrow = bool(re.search(r"\b(tomorrow|next day)\b", _normalize_text(message)))
    snapshot = await get_weather_snapshot(
        city=city,
        country="",
        forecast_days_ahead=1 if is_tomorrow else 0,
    )

    if not snapshot.get("ok"):
        reason = str(snapshot.get("message") or "").strip()
        if not os.getenv("WEATHERMAP_API_KEY", "").strip() and not os.getenv("OPENWEATHERMAP_API_KEY", "").strip():
            reason = "the backend could not read WEATHERMAP_API_KEY or OPENWEATHERMAP_API_KEY from .env."
        period = "tomorrow's forecast" if is_tomorrow else "current weather"
        return f"I could not retrieve {period} for {display_location}: {reason}"

    if is_tomorrow:
        return str(snapshot.get("message") or "Tomorrow's forecast is unavailable.")

    display_location = str(snapshot.get("location_text") or display_location)
    description = str(snapshot.get("description") or "unknown weather").strip()
    temp = str(snapshot.get("temp") or "?").strip()
    feels_like = str(snapshot.get("feels_like") or "?").strip()
    humidity = str(snapshot.get("humidity") or "?").strip()
    wind_kmh = str(snapshot.get("wind_kmh") or "?").strip()

    return (
        f"Current weather in {display_location}: {description}, {temp} C "
        f"(feels like {feels_like} C), humidity {humidity}%, "
        f"and wind around {wind_kmh} km/h."
    )


def _build_history_messages(session_id: str) -> list[ChatMessage]:
    snapshot = get_agent_console_service().get_snapshot(session_id=session_id)
    history: list[ChatMessage] = []

    for item in snapshot.get("messages", [])[-12:]:
        role = item.get("role")
        content = str(item.get("content") or "").strip()
        if role not in {"user", "assistant"} or not content:
            continue
        history.append(ChatMessage(role=role, content=content))

    return history


def _build_llm_client() -> OpenAICompatibleChatClient | StaticLLMClient:
    if os.getenv("OPENAI_API_KEY") or os.getenv("FRIDAY_LLM_API_KEY"):
        return OpenAICompatibleChatClient(
            provider=os.getenv("FRIDAY_LLM_PROVIDER", "openai-compatible")
        )

    return StaticLLMClient(
        content=LLM_NOT_CONFIGURED_MESSAGE,
        provider="not-configured",
    )


@lru_cache(maxsize=1)
def _get_news_service() -> NewsService:
    return NewsService(
        api_key=config.NEWSDATA_API_KEY,
        world_api_key=config.WORLD_NEWS,
        default_language=config.NEWS_DEFAULT_LANGUAGE,
        default_country=config.NEWS_DEFAULT_COUNTRY,
        default_limit=config.NEWS_DEFAULT_LIMIT,
        timeout_seconds=config.NEWS_REQUEST_TIMEOUT,
    )


def _get_news_result(message: str):
    try:
        return _get_news_service().handle_user_query(message)
    except Exception:
        return None


def _build_news_context_from_result(result) -> str:
    if result is None:
        return ""

    if not result.is_news_intent:
        return ""

    if result.agent_context:
        return result.agent_context

    if result.fallback_message:
        return (
            "[NEWS_CONTEXT]\n"
            f"status={result.status}\n"
            f"fallback_user_message={result.fallback_message}\n"
            "response_rules=Reply briefly in English without exposing implementation details."
        )

    return ""


def _build_llm_error_message(exc: Exception) -> str:
    return (
        "I could not call the LLM provider from the backend. "
        f"Technical error: {type(exc).__name__}. "
        "Check OPENAI_API_KEY/FRIDAY_LLM_API_KEY, FRIDAY_LLM_BASE_URL, and model settings in the backend .env file."
    )


def _format_startup_news_digest() -> str:
    try:
        result = _get_news_service().handle_user_query("today's news in Vietnam")
    except Exception:
        return "News: the feed is unstable, and I will retry when the connection improves."

    if result.articles:
        lines = []
        for index, article in enumerate(result.articles[:3], start=1):
            title = str(article.title or "").strip()
            source = str(article.source_name or article.source_id or "news source").strip()
            if title:
                lines.append(f"{index}. {title} ({source})")
        if lines:
            return "Top stories:\n" + "\n".join(lines)

    fallback = str(result.fallback_message or "").strip()
    if fallback:
        return f"News: {fallback}"
    return "News: no relevant top stories are available right now."


async def build_startup_briefing() -> str:
    now = datetime.now()
    location = resolve_runtime_location()
    weather_reply = await _build_weather_reply(f"weather in {location.city}")
    news_digest = await asyncio.to_thread(_format_startup_news_digest)

    return (
        f"FRIDAY is online at {now:%H:%M}. I completed a quick live-data check.\n\n"
        f"{weather_reply}\n\n"
        f"{news_digest}\n\n"
        "Do you have a schedule, appointment, or priority you would like me to track today?"
    )


async def chat(payload: ConsoleChatRequest) -> dict:
    power_intent = detect_power_intent(payload.message)
    power_result = handle_power_message(
        payload.message,
        source=f"web:{payload.session_id}",
        silent_when_sleeping=payload.channel == "voice",
    )
    if power_result.handled:
        if power_intent == PowerIntent.WAKE:
            await asyncio.to_thread(restore_application_windows)
        if not power_result.reply:
            return get_agent_console_service().get_snapshot(session_id=payload.session_id)
        return get_agent_console_service().send_assistant_reply(
            payload,
            assistant_content=power_result.reply,
        )

    if is_binance_market_request(payload.message):
        binance_result = await asyncio.to_thread(run_binance_market, payload.message)
        return get_agent_console_service().send_assistant_reply(
            payload,
            assistant_content=binance_result.message,
        )

    if is_platform_video_search_request(payload.message):
        video_result = await asyncio.to_thread(
            run_platform_video_search,
            payload.message,
        )
        return get_agent_console_service().send_assistant_reply(
            payload,
            assistant_content=video_result.message,
        )

    if is_browser_search_request(payload.message):
        browser_result = await asyncio.to_thread(run_browser_search, payload.message)
        return get_agent_console_service().send_assistant_reply(
            payload,
            assistant_content=browser_result.message,
        )

    if is_messenger_latest_request(payload.message):
        messenger_result = await asyncio.to_thread(check_latest_messenger_message)
        return get_agent_console_service().send_assistant_reply(
            payload,
            assistant_content=messenger_result.message,
        )

    if is_screen_understanding_request(payload.message):
        screen_reply = await understand_current_screen(payload.message)
        return get_agent_console_service().send_assistant_reply(
            payload,
            assistant_content=screen_reply,
        )

    if is_social_open_request(payload.message):
        social_reply = await asyncio.to_thread(open_social_platform, payload.message)
        return get_agent_console_service().send_assistant_reply(
            payload,
            assistant_content=social_reply,
        )

    if _is_computer_command(payload.message):
        return send_console_message(payload)

    about_match = match_about_response(payload.message, response_type="voice")
    if about_match.matched:
        return get_agent_console_service().send_assistant_reply(
            payload,
            assistant_content=about_match.response,
        )

    if _is_weather_command(payload.message):
        weather_reply = await _build_weather_reply(payload.message)
        return get_agent_console_service().send_assistant_reply(
            payload,
            assistant_content=weather_reply,
        )

    if _is_gmail_command(payload.message):
        result = await check_unread_gmail_with_timeout()
        return get_agent_console_service().send_assistant_reply(
            payload,
            assistant_content=format_gmail_voice_report(result),
        )

    history = _build_history_messages(payload.session_id)
    workspace_context = build_workspace_context(payload.message)
    news_result = await asyncio.to_thread(_get_news_result, payload.message)
    news_context = _build_news_context_from_result(news_result)
    web_research_context = ""
    research_failure = ""

    should_fallback_from_news = bool(
        news_result
        and news_result.is_news_intent
        and news_result.status in {"error", "no_data"}
    )
    should_research_question = bool(
        (news_result is None or not news_result.is_news_intent)
        and is_web_research_request(payload.message)
    )
    if should_fallback_from_news or should_research_question:
        research_result = await asyncio.to_thread(research_public_web, payload.message)
        web_research_context = build_web_research_context(research_result)
        if web_research_context:
            news_context = ""
        elif should_research_question:
            research_failure = research_result.message

    if research_failure:
        return get_agent_console_service().send_assistant_reply(
            payload,
            assistant_content=research_failure,
        )

    messages = [
        ChatMessage(role="system", content=REST_AGENT_SYSTEM_PROMPT),
        ChatMessage(role="system", content=workspace_context),
        *([ChatMessage(role="system", content=news_context)] if news_context else []),
        *(
            [ChatMessage(role="system", content=web_research_context)]
            if web_research_context
            else []
        ),
        *history,
        ChatMessage(role="user", content=payload.message.strip()),
    ]
    request = LLMRequest(
        messages=messages,
        model=os.getenv("FRIDAY_AGENT_MODEL", os.getenv("OPENAI_MODEL", "gpt-4o-mini")),
        temperature=float(os.getenv("FRIDAY_AGENT_TEMPERATURE", "0.35")),
        max_tokens=int(os.getenv("FRIDAY_AGENT_MAX_TOKENS", "900")),
    )

    try:
        response = await _build_llm_client().complete(request)
        content = response.content.strip()
    except Exception as exc:
        content = _build_llm_error_message(exc)

    if not content:
        content = (
            "The LLM provider returned an empty response. "
            "Try a shorter question or check the configured model."
        )

    return get_agent_console_service().send_assistant_reply(
        payload,
        assistant_content=content,
    )


